// Emits the committed firmware art header (TroupeArtData.h) and the Lua test
// stub that mirrors the firmware's `troupe` module. The resident art set is
// every actor with authored art.
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { ROOT, parseCli, runCli } from "./lib/cli";
import { loadPalette, loadActor, type ActorSprites, type Palette } from "./lib/sprites";
import { emitPaletteChunk, emitActorChunk, troupeArtFingerprint } from "./gen-sprite-data";

export const HEADER_PATH = "device/lib/drivers/src/TroupeArtData.h";

export function loadAllActors(): { actors: ActorSprites[]; palette: Palette } {
  const palette = loadPalette(path.join(ROOT, "sprites/palette.json"));
  const ids = readdirSync(path.join(ROOT, "sprites/actors"), { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();
  return { actors: ids.map((id) => loadActor(path.join(ROOT, "sprites/actors", id), palette)), palette };
}

export function emitTroupeHeader(): string {
  const { actors, palette } = loadAllActors();
  const fp = troupeArtFingerprint(actors, palette);
  const lines: string[] = [];
  lines.push("// generated by tools/gen-troupe-header.ts -- do not edit");
  lines.push("// regenerate: npm run gen:troupe (a stale header fails tests/gen-troupe-header.test.ts)");
  lines.push("#pragma once");
  lines.push("#include <cstddef>");
  lines.push("");
  lines.push("namespace troupe_art {");
  lines.push("");
  lines.push(`inline constexpr const char* kFingerprintHex = "${fp}";`);
  lines.push("");
  lines.push(`inline constexpr const char* kPaletteChunk = R"LUA(${emitPaletteChunk(palette)})LUA";`);
  lines.push("");
  lines.push("struct ActorChunk { const char* id; const char* chunk; };");
  lines.push("");
  lines.push("inline constexpr ActorChunk kActors[] = {");
  for (const a of actors) {
    lines.push(`  {"${a.id}", R"LUA(${emitActorChunk(a)})LUA"},`);
  }
  lines.push("};");
  lines.push("inline constexpr size_t kActorCount = sizeof(kActors) / sizeof(kActors[0]);");
  lines.push("");
  lines.push("}  // namespace troupe_art");
  return lines.join("\n") + "\n";
}

// Mirrors TroupeArtDriver::install / ::fingerprint for headless Lua test
// harnesses (tests/lua/*). Behavior must track the C++ driver exactly:
// palette first, then S.sprites = {}, then each requested actor; unknown
// ids are an error.
export function emitTroupeStubLua(fingerprint?: string): string {
  const { actors, palette } = loadAllActors();
  const fp = fingerprint ?? troupeArtFingerprint(actors, palette);
  const lines: string[] = [];
  lines.push("-- generated by tools/gen-troupe-header.ts (emitTroupeStubLua) -- test stub");
  // The firmware's driver is native code, outside the app sandbox, so the
  // stub keeps its own `load` for when the sim removes the global.
  lines.push("local load = load");
  lines.push("troupe = {}");
  lines.push(`function troupe.fingerprint() return "${fp}" end`);
  lines.push(`local palette_chunk = [==[\n${emitPaletteChunk(palette)}]==]`);
  lines.push("local chunks = {");
  for (const a of actors) {
    lines.push(`  ${a.id} = [==[\n${emitActorChunk(a)}]==],`);
  }
  lines.push("}");
  lines.push("function troupe.install(S, ids)");
  lines.push("  S.palette = assert(load(palette_chunk))()");
  lines.push("  S.sprites = {}");
  lines.push("  for i = 1, #ids do");
  lines.push('    local c = chunks[ids[i]] or error("troupe.install: unknown actor \'" .. ids[i] .. "\'")');
  lines.push("    S.sprites[ids[i]] = assert(load(c))()");
  lines.push("  end");
  lines.push("end");
  return lines.join("\n") + "\n";
}

export function main(argv: string[]): void {
  parseCli(argv, { usage: "usage: npm run gen:troupe" });
  writeFileSync(path.join(ROOT, HEADER_PATH), emitTroupeHeader());
  console.log(`${HEADER_PATH} written`);
}

runCli(import.meta.url, main);
