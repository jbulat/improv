// Extracts M5GFX's default Font0 (classic GLCD 5x7 in a 6x8 cell) into
// tools/lib/gfx-font-data.ts. Run once; the output is committed so the
// simulator needs no PlatformIO at runtime.
//   npx tsx tools/gen-gfx-font.ts [--libdeps device/.pio/libdeps]
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { ROOT, parseCli, runCli } from "./lib/cli";

export const EXPECTED_BYTES = 1280; // 256 glyphs x 5 columns

/**
 * Every file under `dir` whose name mentions a font: any path matching
 * /glcdfont/i (the Adafruit GLCD table M5GFX vendors as Font0) first, then the
 * rest alphabetically, so "first 1280-byte array wins" (see extractTable)
 * does not depend on filesystem walk order.
 */
export function fontSources(dir: string): string[] {
  const out: string[] = [];
  const walk = (d: string) => {
    let entries: string[];
    try {
      entries = readdirSync(d);
    } catch {
      return;
    }
    for (const name of entries) {
      const full = path.join(d, name);
      let st;
      try {
        st = statSync(full);
      } catch {
        continue;
      }
      if (st.isDirectory()) walk(full);
      else if (/font/i.test(name) && /\.(c|cpp|h|hpp|inl)$/i.test(name)) out.push(full);
    }
  };
  walk(dir);
  out.sort((a, b) => {
    const aGlcd = /glcdfont/i.test(a);
    const bGlcd = /glcdfont/i.test(b);
    if (aGlcd !== bGlcd) return aGlcd ? -1 : 1;
    return a < b ? -1 : a > b ? 1 : 0;
  });
  return out;
}

/**
 * Pull the first byte array of exactly EXPECTED_BYTES entries out of C source.
 * The classic GLCD table is the only 1280-byte array in these files, which is
 * what makes "first match wins" safe.
 */
export function extractTable(source: string): number[] | null {
  const arrayRe = /\{([^{}]*?)\}/gs;
  for (const m of source.matchAll(arrayRe)) {
    const body = m[1];
    if (!/0[xX][0-9a-fA-F]/.test(body)) continue;
    const bytes = [...body.matchAll(/0[xX]([0-9a-fA-F]{1,2})/g)].map((b) => parseInt(b[1], 16));
    if (bytes.length === EXPECTED_BYTES) return bytes;
  }
  return null;
}

