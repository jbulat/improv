export function emitFontData(bytes: number[]): string {
  const rows: string[] = [];
  for (let i = 0; i < bytes.length; i += 20) {
    rows.push(
      "  " +
        bytes
          .slice(i, i + 20)
          .map((b) => String(b))
          .join(", ") +
        ",",
    );
  }
  return (
    "// tools/lib/gfx-font-data.ts\n" +
    "// GENERATED by tools/gen-gfx-font.ts -- do not edit.\n" +
    "// M5GFX default font (Font0): the classic GLCD 5x7 glyph in a 6x8 cell.\n" +
    "// 256 glyphs x 5 column bytes; bit 0 of each byte is the top pixel.\n" +
    "//\n" +
    "// Table data is Adafruit's classic GLCD 5x7 font (glcdfont.h), vendored\n" +
    "// here via M5GFX (device/.pio/libdeps/*/M5GFX). Its licence follows, as\n" +
    "// the licence requires.\n" +
    "//\n" +
    ADAFRUIT_LICENSE.map((l) => (l ? "// " + l : "//")).join("\n") +
    "\n\n" +
    "export const GLYPH_COUNT = 256;\n\n" +
    "export const GFX_FONT = new Uint8Array([\n" +
    rows.join("\n") +
    "\n]);\n"
  );
}

export function main(argv: string[]): number | void {
  const { values } = parseCli(argv, {
    usage: "usage: npx tsx tools/gen-gfx-font.ts [--libdeps <dir>]",
    options: { libdeps: { type: "string", default: path.join(ROOT, "device/.pio/libdeps") } },
  });
  const { libdeps } = values;
  const candidates = fontSources(libdeps);
  if (candidates.length === 0) {
    console.error(`no font sources under ${libdeps} — run "cd device && pio pkg install" first`);
    return 1;
  }
  for (const file of candidates) {
    const bytes = extractTable(readFileSync(file, "utf8"));
    if (!bytes) continue;
    const out = path.join(ROOT, "tools/lib/gfx-font-data.ts");
    writeFileSync(out, emitFontData(bytes));
    console.log(`${path.relative(ROOT, out)} <- ${file} (${bytes.length} bytes)`);
    return;
  }
  console.error(`no ${EXPECTED_BYTES}-byte table in ${candidates.length} font source(s) under ${libdeps}`);
  return 1;
}

runCli(import.meta.url, main);
